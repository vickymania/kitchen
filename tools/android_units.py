"""Write the unit labels of the Android widget from the web app's i18n files.

public/i18n/en.json and nl.json are the one source of how a unit is shown;
android/app/src/main/res/values/units.xml (English) and values-nl/units.xml
(Dutch) are generated from them, never edited by hand.

    py tools/android_units.py           write both files
    py tools/android_units.py --check   exit 1 when they differ from the JSON
"""
import json
import os
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGETS = {"en": "values", "nl": "values-nl"}


def render(lang):
    with open(os.path.join(ROOT, "public", "i18n", f"{lang}.json"), encoding="utf-8") as f:
        units = json.load(f)["units"]
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           f"<!-- Generated by tools/android_units.py from public/i18n/{lang}.json. Do not edit. -->",
           "<resources>"]
    for code, label in units.items():
        one, other = (label["one"], label["other"]) if isinstance(label, dict) else (label, label)
        out.append(f'    <plurals name="unit_{code}">')
        out.append(f'        <item quantity="one">{escape(one)}</item>')
        out.append(f'        <item quantity="other">{escape(other)}</item>')
        out.append("    </plurals>")
    out.append("</resources>")
    return "\n".join(out) + "\n"


def path(lang):
    return os.path.join(ROOT, "android", "app", "src", "main", "res", TARGETS[lang], "units.xml")


def main():
    check = "--check" in sys.argv
    stale = []
    for lang in TARGETS:
        text = render(lang)
        target = path(lang)
        current = open(target, encoding="utf-8").read() if os.path.exists(target) else None
        if current == text:
            continue
        if check:
            stale.append(os.path.relpath(target, ROOT))
        else:
            with open(target, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    if stale:
        print("Android unit labels are out of date, run py tools/android_units.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
